def compile_likec4_config() -> str:
    """Return the canonical `architecture/likec4.config.json` configuration."""
    cfg = {
        "$schema": "https://likec4.dev/schemas/config.json",
        "name": "expensieve-topology",
        "title": "ExpenSieve — Personal Expense Enrichment Engine & Multi-Source Reconciliation Pipeline",
    }
    return json.dumps(cfg, indent=2, ensure_ascii=False) + "\n"


